// ======================= Initialization of UART and LEDs =======================
//
// Здесь мы настраиваем:
// 1) GPIOA: пины PA2 (USART2_TX) и PA3 (USART2_RX) в альтернативную функцию AF7
// 2) GPIOC: пины PC4..PC11 как выходы под 8 светодиодов
// 3) USART2: скорость 19200, включаем RX/TX, включаем прерывание приёма RXNE,
//    разрешаем прерывание в NVIC и включаем USART.
//
// Важно: этот код использует CMSIS-структуры (RCC->..., GPIOA->..., USART2->...),
// поэтому в initialization.h должен быть подключён заголовок stm32f446xx.h.
//
// ==============================================================================

#include "initialization.h"

// -------------------------- Настройки UART ------------------------------------

// Требуемая скорость передачи UART (baud rate)
#define BAUDRATE    19200U

// Частота шины APB (PCLK1) для USART2.
// В STM32F446 USART2 находится на APB1.
// В лабораторной часто считают, что PCLK1 = 16 MHz (если так задано в стенде/проекте).
#define APBx_FREQ   16000000U

// -------------------------- Тактирование GPIO --------------------------------

// Биты включения тактирования GPIOA и GPIOC в регистре RCC->AHB1ENR.
// В STM32F4:
// GPIOAEN — бит 0
// GPIOCEN — бит 2
#define GPIOAEN     (1U << 0)
#define GPIOCEN     (1U << 2)

// =============================================================================
//  Функция GPIOA_Init()
//  Назначение: настроить выводы PA2 и PA3 под USART2
// =============================================================================
void GPIOA_Init(void)
{
    // -------------------- 1) Включаем тактирование GPIOA ----------------------
    // Пока тактирование GPIOA выключено, изменения регистров GPIOA могут:
    // - не применяться
    // - или возвращать "нулевые" значения
    // Поэтому первым делом включаем тактирование порта A.
    RCC->AHB1ENR |= GPIOAEN;

    // -------------------- 2) Настраиваем режим пинов PA2 и PA3 ----------------
    //
    // Регистр GPIOx_MODER управляет режимом каждого пина.
    // На каждый пин выделено 2 бита:
    //   00 — вход (Input)
    //   01 — выход (Output)
    //   10 — альтернативная функция (Alternate Function, AF)
    //   11 — аналоговый режим (Analog)
    //
    // PA2: нужны биты MODER2[1:0] = 10 (AF)
    // PA3: нужны биты MODER3[1:0] = 10 (AF)
    //
    // Ты выставляешь эти пары бит “по одному биту”:
    // - устанавливаешь старший бит пары в 1
    // - младший сбрасываешь в 0
    //
    // PA2 (пин 2): MODER[5]=1, MODER[4]=0 -> "10"
    GPIOA->MODER |=  (1U << 5);   // устанавливаем бит 5
    GPIOA->MODER &= ~(1U << 4);   // сбрасываем бит 4

    // PA3 (пин 3): MODER[7]=1, MODER[6]=0 -> "10"
    GPIOA->MODER |=  (1U << 7);   // устанавливаем бит 7
    GPIOA->MODER &= ~(1U << 6);   // сбрасываем бит 6

    // -------------------- 3) Выбираем альтернативную функцию AF7 --------------
    //
    // Регистр GPIOx_AFRL (AFR[0]) задаёт альтернативную функцию для пинов 0..7.
    // Каждый пин занимает 4 бита.
    //
    // Для USART2 на STM32F446:
    //   PA2 -> USART2_TX -> AF7 (0111)
    //   PA3 -> USART2_RX -> AF7 (0111)
    //
    // Для PA2 используются биты AFRL[11:8]
    // Для PA3 используются биты AFRL[15:12]
    //
    // AF7 = 0b0111:
    //   бит0 = 1
    //   бит1 = 1
    //   бит2 = 1
    //   бит3 = 0
    //
    // То есть мы должны:
    //   - очистить старший бит (бит3)
    //   - выставить три младших бита
    //
    // PA2: AFRL[11]=0, AFRL[10]=1, AFRL[9]=1, AFRL[8]=1
    GPIOA->AFR[0] &= ~(1U << 11); // старший бит AF для PA2 = 0
    GPIOA->AFR[0] |=  (1U << 10); // младшие биты = 1
    GPIOA->AFR[0] |=  (1U << 9);
    GPIOA->AFR[0] |=  (1U << 8);

    // PA3: AFRL[15]=0, AFRL[14]=1, AFRL[13]=1, AFRL[12]=1
    GPIOA->AFR[0] &= ~(1U << 15); // старший бит AF для PA3 = 0
    GPIOA->AFR[0] |=  (1U << 14);
    GPIOA->AFR[0] |=  (1U << 13);
    GPIOA->AFR[0] |=  (1U << 12);

    // После этого PA2/PA3 работают как линии USART2 (TX/RX).
    // На защите важно: MODER переводит в AF, AFR задаёт номер функции (AF7).
}

// =============================================================================
//  Функция LED_mode_setup()
//  Назначение: настроить PC4..PC11 как выходы под 8 светодиодов
// =============================================================================
void LED_mode_setup(void)
{
    // -------------------- 1) Включаем тактирование GPIOC ----------------------
    RCC->AHB1ENR |= GPIOCEN;

    // -------------------- 2) PC4..PC11 переводим в Output mode ----------------
    //
    // Как и у GPIOA->MODER, на каждый пин 2 бита:
    //   01 — Output
    //
    // Для PC4: нужны биты MODER4[1:0] = 01
    // Это значит:
    //   бит (4*2)   = бит 8  -> 1
    //   бит (4*2+1) = бит 9  -> 0
    //
    // Повторяем аналогично для PC5..PC11

    // PC4 output (01)
    GPIOC->MODER |=  (1U << 8);
    GPIOC->MODER &= ~(1U << 9);

    // PC5 output (01)
    GPIOC->MODER |=  (1U << 10);
    GPIOC->MODER &= ~(1U << 11);

    // PC6 output (01)
    GPIOC->MODER |=  (1U << 12);
    GPIOC->MODER &= ~(1U << 13);

    // PC7 output (01)
    GPIOC->MODER |=  (1U << 14);
    GPIOC->MODER &= ~(1U << 15);

    // PC8 output (01)
    GPIOC->MODER |=  (1U << 16);
    GPIOC->MODER &= ~(1U << 17);

    // PC9 output (01)
    GPIOC->MODER |=  (1U << 18);
    GPIOC->MODER &= ~(1U << 19);

    // PC10 output (01)
    GPIOC->MODER |=  (1U << 20);
    GPIOC->MODER &= ~(1U << 21);

    // PC11 output (01)
    GPIOC->MODER |=  (1U << 22);
    GPIOC->MODER &= ~(1U << 23);

    // Важно на защите:
    // мы не трогаем кнопки PD2/PC13 здесь — они остаются входами (00) по reset.
}

// =============================================================================
//  Функция USART2_Init()
//  Назначение: включить USART2, настроить baudrate и прерывания при приёме
// =============================================================================
void USART2_Init(void)
{
    // -------------------- 1) Включаем тактирование USART2 ---------------------
    //
    // USART2 сидит на шине APB1, поэтому используем RCC->APB1ENR.
    // Макрос RCC_APB1ENR_USART2EN задаётся в stm32f446xx.h
    RCC->APB1ENR |= RCC_APB1ENR_USART2EN;

    // -------------------- 2) Включаем приёмник и передатчик -------------------
    //
    // Регистр USARTx_CR1 (Control Register 1)
    // - TE (Transmitter Enable) разрешает передатчик
    // - RE (Receiver Enable) разрешает приёмник
    USART2->CR1 |= USART_CR1_TE;   // включить передатчик
    USART2->CR1 |= USART_CR1_RE;   // включить приёмник

    // -------------------- 3) Настраиваем скорость передачи BRR ----------------
    //
    // Регистр USARTx_BRR (Baud Rate Register) определяет делитель скорости.
    // В простом приближении для oversampling=16:
    //   BRR ≈ PCLK / BaudRate
    //
    // Здесь принимаем PCLK1 = 16 MHz (APBx_FREQ).
    // Тогда для 19200 получится около 833.33.
    // В лабораторной часто принимают целую часть.
    //
    // Важно: в реальности BRR имеет mantissa+fraction, и лучше считать точнее,
    // но для лабы может быть достаточно.
    USART2->BRR = (APBx_FREQ / BAUDRATE);

    // -------------------- 4) Разрешаем прерывание RXNE ------------------------
    //
    // RXNE (Receive Data Register Not Empty) — флаг, что в DR есть принятый байт.
    // RXNEIE (RXNE interrupt enable) включает прерывание по RXNE.
    // Тогда при приходе каждого байта сработает USART2_IRQHandler().
    USART2->CR1 |= USART_CR1_RXNEIE;

    // -------------------- 5) Разрешаем IRQ USART2 в контроллере NVIC ----------
    //
    // Даже если RXNEIE включено в USART, прерывания не пойдут,
    // пока NVIC не разрешит линию USART2_IRQn.
    NVIC_EnableIRQ(USART2_IRQn);

    // -------------------- 6) Включаем сам USART (UE = 1) ----------------------
    //
    // UE (USART Enable) — главный "включатель" модуля USART.
    // Пока UE=0, USART не работает.
    USART2->CR1 |= USART_CR1_UE;

    // После этого USART2 готов:
    // - принимает байты (RE=1)
    // - передаёт байты (TE=1)
    // - при приходе байта генерирует прерывание (RXNEIE=1 + NVIC enabled)
}
